CREATE OR REPLACE STORAGE INTEGRATION AZURE_STORAGE_INT
TYPE = EXTERNAL_STAGE
STORAGE_PROVIDER = AZURE
ENABLED = TRUE
AZURE_TENANT_ID = 'ce10ea1f-3566-46ab-8035-5a56a82be5f6'
STORAGE_ALLOWED_LOCATIONS = ('azure://storageaccountsnowflake.blob.core.windows.net/snow/');

DESC STORAGE INTEGRATION AZURE_STORAGE_INT;

SELECT CURRENT_ORGANIZATION_NAME()
       || '-'
       || CURRENT_ACCOUNT_NAME()
       AS ACCOUNT_IDENTIFIER;

CREATE DATABASE IF NOT EXISTS AZURE_DEMO_DB;

CREATE SCHEMA IF NOT EXISTS AZURE_DEMO_DB.RAW;

USE DATABASE AZURE_DEMO_DB;
USE SCHEMA RAW;

CREATE OR REPLACE STAGE AZURE_SNOW_STAGE
URL = 'azure://storageaccountsnowflake.blob.core.windows.net/snow/'
STORAGE_INTEGRATION = AZURE_STORAGE_INT;

LIST @AZURE_SNOW_STAGE;

LIST @AZURE_SNOW_STAGE/config/;

LIST @AZURE_SNOW_STAGE/inbound/customer_billing/;

